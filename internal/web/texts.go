// texts are the translations of the web interface. It speaks German and
// English only (ADR 0003); every key must exist in both (see texts_test.go).
var texts = map[string]map[string]string{
	"de": textsDE,
	"en": textsEN,
}

func tr(lang, key string, args ...any) string {
	m, ok := texts[lang]
	if !ok {
		m = texts["en"]
	}
	s, ok := m[key]
	if !ok {
		return key
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}

func hasText(lang, key string) bool {
	_, ok := texts[lang][key]
	return ok
}

var funcs = template.FuncMap{
	"date": fmtDate,
	"datetime": func(lang string, t time.Time) string {
		if t.IsZero() {
			return "–"
		}
		if lang == "de" {
			return t.Format("02.01.2006 15:04")
		}
		return t.Format("2006-01-02 15:04")
	},
	"pct": func(f float64) string { return fmt.Sprintf("%.0f %%", 100*f) },
	"num": func(f float64) string {
		return strings.TrimSuffix(strings.TrimSuffix(fmt.Sprintf("%.1f", f), "0"), ".")
	},
	"join": strings.Join,
	"add":  func(a, b int) int { return a + b },
	"seq": func(n int) []int {
		out := make([]int, n)
		for i := range out {
			out[i] = i
		}
		return out
	},
}

